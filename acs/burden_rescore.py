"""Exploratory re-score under rulebook v1.5: ABS-V1, the tiered burden of proof (founder ruling 2, 2026-11-04).

Applies ABS-V1 to stored labels and cases; no model call. Written after every label and record had been seen, by the
author side: exploratory, never confirmatory, and no historical number is changed. The report is the addendum of
`results/LABEL_ADJUDICATION_2026-11-04.md`, generated by `python3 -m acs.label_adjudication`.

One cell is one stored case at one evidence level. ABS-V1 applies to it when
  * the claim is a merchant-performance claim in ABS-V1's scope (`acs.rule_engine.burden_scope` on the claim text:
    non-delivery or non-conformity and nothing else, the agent not named);
  * no record with independent authority shown at that level supports the merchant on the contested fact: every such
    record in the package `acs.evidence.build_bundle` builds for the level is cited for a merchant-favourable finding
    and read by the engine's own `acs.rule_engine.step1_support` (gate v3 readers);
  * the order value (the case's transaction amount, EUR) is at or below the threshold, and the buyer is under the cap.
    No stored case carries a buyer history, so every buyer counts zero earlier ABS-V1 refunds and the cap never binds.
Where it applies the label becomes AG3 / merchant / refund; elsewhere the v1.4 label stands (above the threshold v1.5
is v1.4).
"""

from __future__ import annotations

import json
import os
from collections import defaultdict

from . import analyze_phase2 as p2
from .evidence import build_bundle
from .rule_engine import burden_parameters, burden_scope, burden_tier, step1_support
from .scenarios import DATA_DIR

AG3_REFUND = {"reason_code": "AG3", "liable_party": "merchant", "remedy": "refund"}
DEFAULT_THRESHOLD = 100.0
NO_THRESHOLD = 1e9  # sensitivity: every order value is 'low' (the founder's labels applied the burden view at any value)
SENSITIVITY = (DEFAULT_THRESHOLD, 250.0, 500.0, NO_THRESHOLD)
# Phase 3 case-sides (results/PHASE3_ATTACKS.md, design): the side that lied and was optimised.
PHASE3_MERCHANT_SIDE = ("D01", "D02", "D05", "D06", "D08", "D09", "D10")
PHASE3_BUYER_SIDE = ("D45", "D46", "D47", "D48", "D49", "D50", "D51")
_INDEPENDENT_DELIVERY = ("carrier_proof_of_delivery", "serial_registry", "digital_delivery_log", "return_inspection")
_CONFORMITY_ATTRS = ("brand", "model", "colour", "condition", "key_specs", "appearance_vs_images", "damage", "included_accessories", "quantity")


def threshold_label(t: float) -> str:
    return "none" if t >= NO_THRESHOLD else f"EUR {t:,.0f}"


def source_cases() -> dict:
    out = {}
    for name in ("cases.json", "capture_cases.json"):
        with open(os.path.join(DATA_DIR, "disputes", name), encoding="utf-8") as fh:
            out.update({c["case_id"]: c for c in json.load(fh)["cases"]})
    return out


def merchant_favourable_findings(bundle: dict, scope: dict) -> list[dict]:
    """One merchant-favourable finding per contested fact and per record with independent authority in the package."""
    from .provenance import ATTRIBUTE_CUES_V3
    attrs = sorted({m for name, _, ms in ATTRIBUTE_CUES_V3 if name in scope["attributes"] for m in ms}) or list(_CONFORMITY_ATTRS)
    out = []
    for pid, recs in sorted(((bundle.get("delivery_evidence") or {}).get("by_product") or {}).items()):
        for kind in _INDEPENDENT_DELIVERY:
            if kind not in recs:
                continue
            path = f"delivery_evidence.by_product.{pid}.{kind}"
            if "non_delivery" in scope["kinds"]:
                out.append({"finding": "delivery_status", "value": "delivered", "evidence": [path]})
            if "non_conformity" in scope["kinds"]:
                out += [{"finding": f"conformity:{a}", "value": True, "evidence": [path]} for a in attrs]
    return out


def cell(case: dict, level: str, threshold: float = DEFAULT_THRESHOLD, prior_refunds: int = 0) -> dict:
    """ABS-V1 on one stored case at one level: {"in_scope", "merchant_support", "order_value", "tier", "applies", "why"}."""
    bundle = build_bundle(case, level)
    tx = case["dispute"]["transaction"]
    scope = burden_scope(None, case["dispute"]["buyer_claim"], bundle)
    base = {"case_id": case["case_id"], "level": level, "order_value": tx["amount"], "currency": tx.get("currency", "EUR"),
            "in_scope": scope["in_scope"], "merchant_support": [], "tier": None, "applies": False}
    if not scope["in_scope"]:
        return {**base, "why": scope["why"]}
    sup = step1_support(merchant_favourable_findings(bundle, scope), scope, bundle)
    if sup["merchant"]:
        return {**base, "merchant_support": sorted({m["finding"] for m in sup["merchant"]}), "why": "an independent record supports the merchant"}
    params = burden_parameters("1.5", {"low_value_threshold": {"EUR": threshold}})
    tier = burden_tier(tx["amount"], base["currency"], prior_refunds, params)
    return {**base, "tier": tier["tier"], "applies": tier["tier"] == "low_value", "why": tier["why"]}


def label_v15(v14_label: dict, c: dict) -> dict:
    return dict(AG3_REFUND) if c["applies"] else {k: v14_label[k] for k in ("reason_code", "liable_party", "remedy")}


def kit(adj_cases: dict, threshold: float = DEFAULT_THRESHOLD) -> dict:
    """kit id -> {"label" (v1.5), "v14" (adjudicated v1.4 label), "cell"} for the 40 expert-kit cells."""
    src = source_cases()
    out = {}
    for aid, k in adj_cases.items():
        c = cell(src[k["case_id"]], k["level"], threshold)
        out[aid] = {"label": label_v15(k["ground_truth"], c), "v14": k["ground_truth"], "cell": c}
    return out


def changed(rows: dict) -> list[str]:
    """Kit ids whose liable party or remedy changes from the v1.4 label (a code-only change is listed apart)."""
    return [aid for aid, r in rows.items() if any(r["label"][f] != r["v14"][f] for f in ("liable_party", "remedy"))]


def code_only(rows: dict) -> list[str]:
    return [aid for aid, r in rows.items() if aid not in changed(rows) and r["label"]["reason_code"] != r["v14"]["reason_code"]]


def phase2(adj_cases: dict, threshold: float = DEFAULT_THRESHOLD, prefix: str | None = None) -> dict:
    """The Phase 2 A1 grid (51 cases x E0-E3) under v1.5, liable party, two keys:
      * simulated facts: the v1.4 labels with the case-level ground-truth correction (D37), as `rescore_phase2`'s v14c;
        v1.5 changes a cell where ABS-V1 applies and the label is not already the merchant's refund;
      * evidence-conditional: the adjudicated kit cells whose liable party is undetermined, less those ABS-V1 decides.
    Returns {"cells", "changes", "by": {(arbiter, level): counts}}."""
    prefix = prefix or p2.PREFIX
    cases = p2.load_cases()
    v14 = {cid: p2.v14_ground_truth(c) for cid, c in cases.items()}
    corrected = {cid: {k: g[k] for k in ("reason_code", "liable_party", "remedy")} for cid, g in v14.items()}
    for k in adj_cases.values():
        a = k.get("adjudication")
        if a and a["class"] == "ground-truth error" and k["source"] == "v3":
            corrected[k["case_id"]] = {f: k["ground_truth"][f] for f in ("reason_code", "liable_party", "remedy")}
    cells = {(cid, lv): cell(c, lv, threshold) for cid, c in cases.items() for lv in p2.LEVELS}
    v15 = {key: label_v15(corrected[key[0]], c) for key, c in cells.items()}
    changes = sorted((cid, lv, corrected[cid]["liable_party"], v15[(cid, lv)]["liable_party"]) for (cid, lv) in cells
                     if any(v15[(cid, lv)][f] != corrected[cid][f] for f in ("liable_party", "remedy")))
    undecidable14 = {(k["case_id"], k["level"]) for k in adj_cases.values() if k["source"] == "v3" and k["ground_truth"]["liable_party"] == "undetermined"}
    undecidable15 = {key for key in undecidable14 if not cells[key]["applies"]}
    by = defaultdict(list)
    for r in p2.load(f"{prefix}_a1_grid"):
        if r["decision"]:
            by[(r["arbiter"], r["level"])].append(r)
    out = {}
    for (arb, lv), rs in by.items():
        ok = {id(r): p2.contract_valid(r, cases) for r in rs}
        right = lambda r, lab: ok[id(r)] and r["decision"]["liable_party"] == lab
        dec14 = [r for r in rs if (r["case_id"], lv) not in undecidable14]
        dec15 = [r for r in rs if (r["case_id"], lv) not in undecidable15]
        newly = [r for r in rs if (r["case_id"], lv) in undecidable14 - undecidable15]
        out[(arb, lv)] = {
            "n": len(rs),
            "v14c": sum(right(r, corrected[r["case_id"]]["liable_party"]) for r in rs),
            "v15": sum(right(r, v15[(r["case_id"], lv)]["liable_party"]) for r in rs),
            "dec14": sum(right(r, corrected[r["case_id"]]["liable_party"]) for r in dec14), "dec14_n": len(dec14),
            "dec15": sum(right(r, v15[(r["case_id"], lv)]["liable_party"]) for r in dec15), "dec15_n": len(dec15),
            "newly": sorted(r["case_id"] for r in newly),
            "newly_right": sum(right(r, v15[(r["case_id"], lv)]["liable_party"]) for r in newly),
        }
    return {"cells": cells, "changes": changes, "by": out, "applies": sorted(k for k, c in cells.items() if c["applies"]),
            "in_scope": sorted({cid for (cid, _), c in cells.items() if c["in_scope"]})}


def phase3_sides(threshold: float = DEFAULT_THRESHOLD) -> dict:
    """The 14 Phase 3 case-sides at E3 (the level of the main arm): which ABS-V1 would decide, by the side that lied."""
    src = source_cases()
    return {side: {cid: cell(src[cid], "E3", threshold) for cid in ids}
            for side, ids in (("merchant", PHASE3_MERCHANT_SIDE), ("buyer", PHASE3_BUYER_SIDE))}
