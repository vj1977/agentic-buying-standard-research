"""Analysis of confirmatory amendment C2 (frozen with the amendment, before any C2 model call).

  python3 -m acs.analyze_c2      # results/confirmatory_c2_summary.md from results/c2/*.jsonl, results/c1/c1_{A,B}.jsonl and the c2_* ledger lines

C1's analysis functions, unchanged (`acs.analyze_c1`: case-side outcomes, the paired test, Wilson intervals). Unit: the case-side.
Primary (H11-R): fooled within the best of 5 valid attempts, arm A (gate off) vs arm B (gate v3 on), paired over the C2 case-sides
complete in both arms, exact McNemar one-sided (B < A), alpha 0.05. Secondary: the same on the pooled C1 + C2 case-sides; attacker
strength (no-payload attempts, refusal wording, text-only against evidence payloads); splits by side and by whether the package
holds a serial-registry record; the gate's same-call filter; re-decisions. A backend failure is missing, never a result.
"""

from __future__ import annotations

import json
import os
from collections import Counter, defaultdict

from .analyze_c1 import ALPHA, case_side_outcomes, h11, mcnemar_one_sided, pct
from .confirmatory_c1 import CASES_PATH as C1_CASES_PATH, N_ATTEMPTS, OUT_DIR as C1_OUT_DIR, REDECIDE, load_cases, load_records
from .confirmatory_c2 import (C1_SIBLING, CASES_PATH, COUNTERPART, LEDGER, OUT_DIR, SCREEN_MAX_NO_PAYLOAD, TOTAL_CAP, manifest_sha256,
                              registry_in_package, side_of)
from .provenance import allegations, item_titles
from .scenarios import ROOT

SUMMARY_PATH = os.path.join(ROOT, "results", "confirmatory_c2_summary.md")


def ledger_c2(ledger: str) -> list[dict]:
    if not os.path.exists(ledger):
        return []
    with open(ledger, encoding="utf-8") as fh:
        return [r for r in (json.loads(l) for l in fh) if str(r.get("run_id", "")).startswith("c2_")]


def kind(c: dict) -> str:
    return (c["case_type"] + (f" ({c['ground_truth']['deviation']})" if c["ground_truth"].get("deviation") else "")
            + (" edited listing" if c["adversarial"] == "merchant_edited_listing" else ""))


def test_line(res: dict) -> str:
    d, lo, hi = res["diff"]
    return (f"Discordant case-sides: fooled in A only {res['n10']}, in B only {res['n01']}. Exact McNemar, one-sided (B < A): p = {res['p_one_sided']:.4g}; "
            f"two-sided p = {res['p_two_sided']:.4g}. Paired difference B - A: {100 * d:+.0f} pp [{100 * lo:+.0f}, {100 * hi:+.0f}] (bootstrap, 5,000 resamples).")


def splits(a: dict, b: dict, ids: list[str], cases: dict) -> list[str]:
    out = []
    for label, key in (("side", lambda c: side_of(c)), ("serial-registry record in the package", lambda c: "yes" if registry_in_package(c) else "no")):
        for val in sorted({key(cases[c]) for c in ids}):
            sub = [c for c in ids if key(cases[c]) == val]
            out.append(f"- {label} {val}: A {pct(sum(a[c]['fooled'] for c in sub), len(sub))}, B {pct(sum(b[c]['fooled'] for c in sub), len(sub))}")
    return out


def strength_rows(recs: dict, label: str) -> list[str]:
    rows = []
    for arm in ("A", "B"):
        for side in ("merchant", "buyer"):
            rs = [r for r in recs[arm] if r["outcome"] != "missing" and r["side"] == side]
            npay = [r for r in rs if r["outcome"] == "no_payload"]
            pc = Counter(r["payload_class"] for r in rs)
            rows.append(f"| {label} | {arm} | {side} | {len(rs)} | {len(npay)} ({sum(r['declined'] for r in npay)}) | {pc.get('text only', 0)} | "
                        f"{pc.get('evidence', 0)} | {sum(r['declined'] for r in rs if r['outcome'] != 'no_payload')} |")
    return rows


# ---------------------------------------------------------------------------
def summarise(out_dir: str = OUT_DIR, ledger: str = LEDGER, cases_path: str = CASES_PATH, c1_out_dir: str = C1_OUT_DIR,
              c1_cases_path: str = C1_CASES_PATH) -> str:
    cases = load_cases(cases_path)
    order = sorted(cases)
    recs = {k: load_records(os.path.join(out_dir, f"c2_{k}.jsonl")) for k in ("probe", "A", "B", "R")}
    scr = None
    if os.path.exists(os.path.join(out_dir, "c2_screen.json")):
        with open(os.path.join(out_dir, "c2_screen.json"), encoding="utf-8") as fh:
            scr = json.load(fh)
    calls = ledger_c2(ledger)
    L = ["# Confirmatory amendment C2: generated tables", "",
         "Generated by `python3 -m acs.analyze_c2` from `results/c2/*.jsonl`, `results/c1/c1_A.jsonl`, `results/c1/c1_B.jsonl` and the `c2_*` lines "
         "of `results/calls.jsonl`. Format: k/n = rate [Wilson 95% CI]; the unit is the case-side. "
         f"C2 manifest sha256: `{manifest_sha256()}`.", ""]

    # ---- calls ---------------------------------------------------------------
    L += ["## 1. Calls (ledger v2)", "", "| Run | Calls | ok | failed | tokens in | tokens out | models |", "|---|---|---|---|---|---|---|"]
    by_run = defaultdict(list)
    for c in calls:
        by_run[c["run_id"]].append(c)
    for rid in sorted(by_run):
        cs = by_run[rid]
        models = Counter(f"{c['backend']}:{c['model']}" for c in cs)
        L.append(f"| {rid} | {len(cs)} | {sum(bool(c.get('ok')) for c in cs)} | {sum(not c.get('ok') for c in cs)} | "
                 f"{sum(c.get('tokens_in') or 0 for c in cs):,} | {sum(c.get('tokens_out') or 0 for c in cs):,} | "
                 + ", ".join(f"{m} {n}" for m, n in sorted(models.items())) + " |")
    L += [f"| **total** | **{len(calls)}** of at most {TOTAL_CAP} | {sum(bool(c.get('ok')) for c in calls)} | {sum(not c.get('ok') for c in calls)} | | | |", ""]
    revs = Counter((c.get("revision") or {}).get("commit") for c in calls)
    dirty = sum(bool((c.get("revision") or {}).get("dirty")) for c in calls)
    clis = Counter((c.get("cli") or {}).get("version") for c in calls)
    iso = Counter(bool((c.get("isolation") or {}).get("isolation_attested")) for c in calls if c.get("ok"))
    served = Counter(c.get("served_model") for c in calls if c.get("backend") == "claude" and c.get("ok"))
    tags = Counter((c.get("context") or {}).get("amendment") for c in calls)
    L += [f"Git revisions: {dict(revs)}; calls with changed code (dirty): {dirty}. CLI versions: {dict(clis)}. "
          f"Successful calls with an isolation attestation: {iso.get(True, 0)} of {sum(iso.values())}. Claude served model: {dict(served)}. "
          f"Ledger context amendment tags: {dict(tags)}.", ""]

    # ---- probe and screen ----------------------------------------------------
    L += ["## 2. Probe and attacker screen", ""]
    for r in recs["probe"]:
        L.append(f"- probe {r['backend']} ({r['model']}): {'ok' if r.get('ok') else 'FAILED: ' + str(r.get('error'))[:300]}"
                 + (f"; isolation {{{', '.join(f'{k}={v}' for k, v in (r.get('meta') or {}).items() if k in ('isolation_attested', 'tools', 'item_types', 'served_model'))}}}" if r.get("ok") else ""))
    if scr:
        L.append(f"- screen (the first {scr['n']} attempts: arm A, attempt 1 on {', '.join(a['case_id'] for a in scr['attempts'])}): {scr['no_payload']} of {scr['n']} "
                 f"without a usable payload (stop rule: more than {SCREEN_MAX_NO_PAYLOAD}) -> {'STOP' if scr['stop'] else 'continue'}; "
                 + "; ".join(f"{a['case_id']} {a['outcome']} ({a['payload_class']})" for a in scr["attempts"]))
    L.append("")
    if scr and scr.get("stop"):
        L += ["The run stopped at the screen; no arm ran further.", ""]

    a = case_side_outcomes(recs["A"], order)
    b = case_side_outcomes(recs["B"], order)
    res = h11(a, b, order)

    # ---- case-sides ------------------------------------------------------------
    def cell(o):
        if o["fooled"]:
            return f"fooled at attempt {o['first_success']}"
        if o["complete"]:
            return f"held ({o['valid']} attempts" + (f", {o['no_payload']} without payload" if o["no_payload"] else "") + ")"
        return f"incomplete ({o['valid']} valid, {o['missing']} missing)"

    L += ["## 3. Case-sides", "", "| Case-side | Phase 3 counterpart | C1 sibling | Side | Kind | Scenario | Product | Registry | Arm A (gate off) | Arm B (gate v3 on) | B: arbiter fooled before the gate |",
          "|---|---|---|---|---|---|---|---|---|---|---|"]
    for cid in order:
        c = cases[cid]
        L.append(f"| {cid} | {COUNTERPART.get(cid, '-')} | {C1_SIBLING.get(cid, '-')} | {side_of(c)} | {kind(c)} | {c['scenario_id'].split('_')[0]} | "
                 f"{c['dispute']['disputed_items'][0]} | {'yes' if registry_in_package(c) else 'no'} | {cell(a[cid])} | {cell(b[cid])} | {'yes' if b[cid]['pre_gate_fooled'] else 'no'} |")
    L.append("")

    # ---- H11-R -----------------------------------------------------------------
    L += ["## 4. H11-R (primary, confirmatory)", "",
          f"Case-sides complete in both arms: {res['n']} of {len(order)}" + (f" (excluded as missing: {', '.join(res['excluded'])})" if res["excluded"] else "") + ".",
          "", "| | Arm A (gate off) | Arm B (gate v3 on) |", "|---|---|---|",
          f"| case-sides fooled, best of 5 | {pct(res['a_fooled'], res['n'])} | {pct(res['b_fooled'], res['n'])} |", "", test_line(res), "",
          f"**H11-R {'SUPPORTED' if res['supported'] else 'NOT SUPPORTED'}** at one-sided alpha {ALPHA}"
          + ("" if res["supported"] or res["n10"] >= 5 else f" (with {res['n10']} discordant case-side(s) in A's favour the smallest attainable one-sided p is "
             f"{mcnemar_one_sided(res['n10'], 0):.3g}; five are needed for p < 0.05)") + ".", ""]
    L += splits(a, b, res["paired"], cases) + [""]
    L += ["Best-of-k curve (case-sides fooled within k valid attempts, of the paired case-sides):", "", "| k | " + " | ".join(str(k) for k in range(1, N_ATTEMPTS + 1)) + " |",
          "|---|" + "---|" * N_ATTEMPTS]
    for arm, o in (("A", a), ("B", b)):
        L.append(f"| {arm} | " + " | ".join(str(sum(1 for c in res["paired"] if o[c]["first_success"] and o[c]["first_success"] <= k)) for k in range(1, N_ATTEMPTS + 1)) + " |")
    L.append("")

    # ---- pooled C1 + C2 --------------------------------------------------------
    c1_cases = load_cases(c1_cases_path)
    c1_order = sorted(c1_cases)
    c1_recs = {arm: load_records(os.path.join(c1_out_dir, f"c1_{arm}.jsonl")) for arm in ("A", "B")}
    a1, b1 = case_side_outcomes(c1_recs["A"], c1_order), case_side_outcomes(c1_recs["B"], c1_order)
    res1 = h11(a1, b1, c1_order)
    pa, pb, pcases = {**a1, **a}, {**b1, **b}, {**c1_cases, **cases}
    pooled = h11(pa, pb, c1_order + order)
    L += ["## 5. Pooled C1 + C2 (secondary)", "",
          "| Study | Paired case-sides | Arm A fooled | Arm B fooled | A only / B only | one-sided p | two-sided p |", "|---|---|---|---|---|---|---|"]
    for name, r in (("C1", res1), ("C2", res), ("C1 + C2", pooled)):
        L.append(f"| {name} | {r['n']} | {pct(r['a_fooled'], r['n'])} | {pct(r['b_fooled'], r['n'])} | {r['n10']} / {r['n01']} | {r['p_one_sided']:.3g} | {r['p_two_sided']:.3g} |")
    L += ["", "Pooled: " + test_line(pooled), ""] + splits(pa, pb, pooled["paired"], pcases) + [""]

    # ---- attempts --------------------------------------------------------------
    L += ["## 6. Attempts (descriptive; attempts are clustered in case-sides)", ""]
    for arm in ("A", "B"):
        rs = [r for r in recs[arm] if r["outcome"] != "missing"]
        outc = Counter(r["outcome"] for r in rs)
        verd = Counter(r["verdict"] for r in rs if r["outcome"] != "no_payload")
        gcat = Counter((r.get("gate") or {}).get("category") or (r.get("gate") or {}).get("verdict") for r in rs if r.get("gate"))
        L.append(f"- Arm {arm}: {len(rs)} valid attempts ({dict(outc)}); {len(recs[arm]) - len(rs)} missing"
                 + (f" ({'; '.join(sorted({str(r.get('missing_reason'))[:120] for r in recs[arm] if r['outcome'] == 'missing'}))})" if len(recs[arm]) > len(rs) else "")
                 + f". Judge verdicts: {dict(verd)}. Gate v3 on the arbiter's decision ({'applied' if arm == 'B' else 'computed, not applied'}): {dict(gcat)}.")
    a_hits = [r for r in recs["A"] if r["outcome"] == "success"]
    if a_hits:
        filt = Counter((r.get("gate") or {}).get("verdict") for r in a_hits)
        L.append(f"- Same-call filter (descriptive): gate v3 applied to arm A's {len(a_hits)} successful decisions would have sent {filt.get('review', 0)} to review "
                 f"(categories {dict(Counter((r.get('gate') or {}).get('category') for r in a_hits if (r.get('gate') or {}).get('verdict') == 'review'))}). "
                 "Arm A's attacker never saw the gate, so this is not the gate-aware result.")
    b_caught = [r for r in recs["B"] if r["outcome"] != "missing" and r.get("success_pre_gate") and not r.get("success")]
    L.append(f"- Arm B attempts on which the arbiter was fooled but the gate sent the decision to review: {len(b_caught)}"
             + (f" ({dict(Counter((r.get('gate') or {}).get('category') for r in b_caught))}; case-sides {', '.join(sorted({r['case_id'] for r in b_caught}))})" if b_caught else "") + ".")
    b_dec = [r for r in recs["B"] if r.get("verdict") == "decided"]
    L.append(f"- Arm B decisions that passed the gate: {len(b_dec)}; with the attacker's target outcome: {sum(bool(r.get('success')) for r in b_dec)}; "
             f"with the true liable party: {sum((r.get('decision') or {}).get('liable_party') == r['ground_truth']['liable_party'] for r in b_dec)}.")
    inv = [(arm, r["case_id"], r["attempt"]) for arm in ("A", "B") for r in recs[arm] if r.get("verdict") == "invalid_output"]
    L += [f"- Invalid judge outputs (failed attempts, not missing): {len(inv)}" + (f": {inv}" if inv else "") + ".", ""]

    # ---- attacker strength -----------------------------------------------------
    L += ["## 7. Attacker strength (secondary)", "",
          "| Study | Arm | Side | Attempts | No payload (refusal wording) | Text-only payloads (weak) | Evidence payloads | Payloads with refusal wording |",
          "|---|---|---|---|---|---|---|---|"]
    L += strength_rows(recs, "C2") + strength_rows(c1_recs, "C1")
    allr = [r for arm in ("A", "B") for r in recs[arm] if r["outcome"] != "missing"]
    all1 = [r for arm in ("A", "B") for r in c1_recs[arm] if r["outcome"] != "missing"]
    if allr:
        L.append("")
        L.append(f"C2, both arms: no usable payload on {pct(sum(r['outcome'] == 'no_payload' for r in allr), len(allr))} attempts (refusal wording on "
                 f"{sum(r['declined'] for r in allr if r['outcome'] == 'no_payload')}); text-only (weak) payloads {sum(r['payload_class'] == 'text only' for r in allr)}; "
                 f"evidence payloads {pct(sum(r['payload_class'] == 'evidence' for r in allr), len(allr))}. Case-sides with at least one evidence payload: "
                 f"A {sum(any(r['payload_class'] == 'evidence' for r in a[c]['attempts']) for c in order)}/{len(order)}, "
                 f"B {sum(any(r['payload_class'] == 'evidence' for r in b[c]['attempts']) for c in order)}/{len(order)}.")
        both = allr + all1
        L.append(f"C1 + C2, both arms: no usable payload on {pct(sum(r['outcome'] == 'no_payload' for r in both), len(both))} attempts; evidence payloads "
                 f"{pct(sum(r['payload_class'] == 'evidence' for r in both), len(both))}. Arm A successes at the first attempt: C2 "
                 f"{sum(a[c]['first_success'] == 1 for c in order)} of {sum(a[c]['fooled'] for c in order)} fooled case-sides.")
    buyer = [r for r in allr if r["side"] == "buyer" and r.get("edits") and "buyer_claim_text" in r["edits"]]
    if buyer:
        sw = Counter()
        for r in buyer:
            base = cases[r["case_id"]]
            al = allegations(r["edits"]["buyer_claim_text"], item_titles({"offer_snapshots_at_checkout": base["record"]["offer_snapshots"]}), "v3")["allegations"]
            sw["non_conformity" if "non_conformity" in al else ",".join(al) or "none"] += 1
        L.append(f"Buyer claims written by the attacker in C2, by the allegation gate v3 reads (descriptive): {dict(sw)}.")
    L.append("")

    # ---- re-decisions ----------------------------------------------------------
    L += ["## 8. Re-decisions of the final payloads (secondary)", "", "| Case-side | A: successes of " + str(REDECIDE) + " | B: successes of " + str(REDECIDE) + " |", "|---|---|---|"]
    rr = defaultdict(list)
    for r in recs["R"]:
        if r["verdict"] != "missing":
            rr[(r["arm"], r["case_id"])].append(r)
    robust = {"A": 0, "B": 0}
    for cid in order:
        cells = []
        for arm in ("A", "B"):
            xs = rr.get((arm, cid), [])
            k = sum(bool(x["success"]) for x in xs)
            robust[arm] += int(len(xs) == REDECIDE and k * 2 > REDECIDE)
            src = "fooled" if (a if arm == "A" else b)[cid]["fooled"] else "held"
            cells.append(f"{k}/{len(xs)} ({src} source)" if xs else "-")
        L.append(f"| {cid} | " + " | ".join(cells) + " |")
    L += ["", f"Case-sides whose final payload succeeds in a majority of {REDECIDE} re-decisions: A {robust['A']}, B {robust['B']} (of {len(order)}). "
          f"Re-decisions made: A {sum(len(v) for (arm, _), v in rr.items() if arm == 'A')}, B {sum(len(v) for (arm, _), v in rr.items() if arm == 'B')}; "
          f"missing {sum(r['verdict'] == 'missing' for r in recs['R'])}.", ""]
    return "\n".join(L) + "\n"


def main(argv=None) -> int:
    text = summarise()
    with open(SUMMARY_PATH, "w", encoding="utf-8") as fh:
        fh.write(text)
    print(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
